#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn the_empty_string_hashes_to_the_published_digests() {
        // The four canonical empty-input vectors. A padding bug shows up here
        // first, because the whole message is padding.
        assert_eq!(Hash::Md5.digest(b""), "d41d8cd98f00b204e9800998ecf8427e");
        assert_eq!(Hash::Sha1.digest(b""), "da39a3ee5e6b4b0d3255bfef95601890afd80709");
        assert_eq!(
            Hash::Sha256.digest(b""),
            "e3b0c44298fc1c149afbf4c8996fb92427ae41e4649b934ca495991b7852b855"
        );
        assert_eq!(
            Hash::Sha512.digest(b""),
            "cf83e1357eefb8bdf1542850d66d8007d620e4050b5715dc83f4a921d36ce9ce\
             47d0d13c5d85f2b0ff8318d2877eec2f63b931bd47417a81a538327af927da3e"
        );
    }

    #[test]
    fn abc_hashes_to_the_published_digests() {
        assert_eq!(Hash::Md5.digest(b"abc"), "900150983cd24fb0d6963f7d28e17f72");
        assert_eq!(Hash::Sha1.digest(b"abc"), "a9993e364706816aba3e25717850c26c9cd0d89d");
        assert_eq!(
            Hash::Sha256.digest(b"abc"),
            "ba7816bf8f01cfea414140de5dae2223b00361a396177a9cb410ff61f20015ad"
        );
        assert_eq!(
            Hash::Sha512.digest(b"abc"),
            "ddaf35a193617abacc417349ae20413112e6fa4e89a97ea20a9eeee64b55d39a\
             2192992a274fc1a836ba3c23a3feebbd454d4423643ce80e2a9ac94fa54ca49f"
        );
    }

    #[test]
    fn a_message_that_crosses_a_block_boundary_still_hashes() {
        // 56 bytes is the length at which the 64-byte padding no longer fits in
        // the block, so this is the case that catches an off-by-one in `pad64`.
        let text = b"abcdbcdecdefdefgefghfghighijhijkijkljklmklmnlmnomnopnopq";
        assert_eq!(text.len(), 56);
        assert_eq!(
            Hash::Sha256.digest(text),
            "248d6a61d20638b8e5c026930c3e6039a33ce45964ff2167f6ecedd419db06c1"
        );
        assert_eq!(
            Hash::Sha1.digest(text),
            "84983e441c3bd26ebaae4aa1f95129e5e54670f1"
        );
    }

    #[test]
    fn a_long_message_hashes_in_every_block() {
        // A million `a`s, the standard long vector. Slow enough to be worth one
        // test rather than a loop over several lengths.
        let text = vec![b'a'; 1_000_000];
        assert_eq!(
            Hash::Sha1.digest(&text),
            "34aa973cd4c4daa4f61eeb2bdbad27316534016f"
        );
        assert_eq!(
            Hash::Sha256.digest(&text),
            "cdc76e5c9914fb9281a1c7e284d73e67f1809a48a497200e046d39ccc7112cd0"
        );
    }

    #[test]
    fn the_hex_rendering_is_lowercase_and_two_digits_per_byte() {
        assert_eq!(hex(&[0x00, 0x0f, 0xa5, 0xff]), "000fa5ff");
    }

    #[test]
    fn every_hash_names_itself() {
        assert_eq!(Hash::Md5.name(), "MD5");
        assert_eq!(Hash::Sha1.name(), "SHA-1");
        assert_eq!(Hash::Sha256.name(), "SHA-256");
        assert_eq!(Hash::Sha512.name(), "SHA-512");
    }
}
