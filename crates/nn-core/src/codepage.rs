//! The single-byte character sets Notepad++ lists under Encoding >
//! Character sets.
//!
//! Every one of these is ASCII in the low half and a 128-entry table in the
//! high half, which is what lets one type stand for forty-one of them. The
//! multi-byte sets Notepad++ also lists -- Big5, GB2312, Shift-JIS, EUC-KR and
//! Windows 949 -- are absent on purpose: decoding them needs a state machine
//! and a table an order of magnitude larger, and a half-done one would corrupt
//! text rather than display it.
//!
//! The tables are generated from the Unicode Consortium's mappings as shipped
//! with Python's `codecs` module. A byte the mapping leaves undefined becomes
//! U+FFFD, which is what a reader should see for a byte that means nothing in
//! the chosen set.

